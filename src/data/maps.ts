export interface MapStep {
  id: string;
  title: string;
  input: string;
  output: string;
  code: string;
  explanation: string;
  note: string;
  links: { title: string; url: string }[];
}
export interface MapSection {
  id: string;
  title: string;
  description: string;
  mode?: 'sequence' | 'branches';
  steps: MapStep[];
}
export interface LearningMap {
  slug: string;
  title: string;
  description: string;
  question: string;
  sections: MapSection[];
}
const lesson = (id: string, title: string) => ({ title: `読む：${title}`, url: `/learn/${id}/` });
const lab = (id: string, title: string) => ({ title: `動かす：${title}`, url: `/labs/${id}/` });
const api = (id: string, title: string) => ({
  title: `調べる：${title}`,
  url: `/reference/api/${id}/`,
});
const project = (id: string, title: string) => ({
  title: `改造課題：${title}`,
  url: `/projects/${id}/`,
});
function step(
  id: string,
  title: string,
  input: string,
  output: string,
  code: string,
  explanation: string,
  note: string,
  links: MapStep['links'],
): MapStep {
  return { id, title, input, output, code, explanation, note, links };
}

