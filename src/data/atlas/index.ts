const block = (lanes: string[][], label?: string): AtlasBlock => ({ lanes, label });
const edge = (from: string, to: string, kind?: AtlasEdge['kind'], label?: string): AtlasEdge => ({
  from,
  to,
  kind,
  label,
});
function section(
  id: string,
  title: string,
  note: string,
  blocks: AtlasBlock[],
  extra: AtlasEdge[] = [],
  links?: AtlasSection['links'],
): AtlasSection {
  const chains = blocks.flatMap((b) =>
    b.lanes.flatMap((l) => l.slice(1).map((to, i) => edge(l[i], to))),
  );
  return { id, title, note, blocks, edges: [...chains, ...extra], links };
}
